const I18N = {
  lang: (() => { 
    try { return localStorage.getItem('ds_lang') === 'ta' ? 'ta' : 'en'; } 
    catch (e) { return 'en'; } 
  })(),

  t(key) { 
    return (UI[this.lang] && UI[this.lang][key]) ?? UI.en[key] ?? key; 
  },

  apply(root = document) {
    document.documentElement.lang = this.lang === 'ta' ? 'ta' : 'en';
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = this.t(el.dataset.i18nPh); });
    root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', this.t(el.dataset.i18nAria)); });
    
    // Navbar Language Button Text Update
    const lb = document.getElementById('langBtn');
    if (lb) lb.textContent = this.t('lang_btn');
  },

  setLang(l) {
    this.lang = (l === 'ta') ? 'ta' : 'en';
    try { localStorage.setItem('ds_lang', this.lang); } catch (e) {}
    this.apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: this.lang }));
  },

  localize(b) {
    // Slug match with prefix check
    const slug = (b.slug || '').toLowerCase();
    const matchKey = Object.keys(RECIPES_TA).find(k => slug.includes(k) || k.includes(slug));

    if (this.lang === 'ta' && matchKey && RECIPES_TA[matchKey]) {
      const r = RECIPES_TA[matchKey];
      return {
        name: r.name,
        region: r.region,
        description: r.desc,
        ingredients: r.ing,
        steps: r.steps
      };
    }

    // Default to DB English
    const parseSafe = v => (Array.isArray(v) ? v : JSON.parse(v || '[]'));
    return {
      name: b.name,
      region: b.region,
      description: b.description,
      ingredients: parseSafe(b.ingredients || b.ingredients_json),
      steps: parseSafe(b.steps || b.steps_json)
    };
  },

  searchText(b) {
    const slug = (b.slug || '').toLowerCase();
    const matchKey = Object.keys(RECIPES_TA).find(k => slug.includes(k) || k.includes(slug));
    const ta = matchKey ? RECIPES_TA[matchKey] : null;
    return [b.name, b.region, b.description, ta ? ta.name : '', ta ? ta.region : '', ta ? ta.desc : '']
      .filter(Boolean)
      .join(' ')
      .toLowerCase();
  }
};